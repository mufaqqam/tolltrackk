// Builds db/seed.sql from db/toll-points.json plus demo users and trips.
// Run: node scripts/generate-seed.mjs   (PINs/passwords are bcrypt-hashed here; only hashes go in the SQL)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import bcrypt from "bcryptjs";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const data = JSON.parse(fs.readFileSync(path.join(root, "db/toll-points.json"), "utf8"));
const q = (s) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(",")}]::text[]`;

const DEMO = {
  drivers: [
    { no: "104", name: "Mohammad", pin: "2580", rego: "1XT 4KD", acct: "tk-58821" },
    { no: "117", name: "Sam Taylor", pin: "1357", rego: "1YB 7QR", acct: "tk-58821" },
  ],
  admin: { email: "office@tolltrack.app", name: "Priya (Office)", password: "TollTrack-Demo-2026" },
};

const today = `(now() at time zone 'Australia/Melbourne')::date`;
let out = `-- TollTrack demo data. Generated by scripts/generate-seed.mjs. Run after schema.sql.
-- Demo sign-ins: Driver 104 / PIN 2580, Driver 117 / PIN 1357, office@tolltrack.app / TollTrack-Demo-2026

insert into toll_roads (id, name) values
${data.roads.map((r) => `  (${r.id}, ${q(r.name)})`).join(",\n")};

insert into toll_points (id, road_id, name, km, lat, lng, entry_dirs, exit_dirs) values
${data.points.map((p) => `  (${p.id}, ${p.road}, ${q(p.name)}, ${p.km}, ${p.lat}, ${p.lng}, ${arr(p.entry)}, ${arr(p.exit)})`).join(",\n")};

insert into users (role, full_name, driver_no, email, secret_hash, truck_rego, toll_account) values
${DEMO.drivers.map((d) => `  ('driver', ${q(d.name)}, ${q(d.no)}, null, ${q(bcrypt.hashSync(d.pin, 10))}, ${q(d.rego)}, ${q(d.acct)})`).join(",\n")},
  ('admin', ${q(DEMO.admin.name)}, null, ${q(DEMO.admin.email)}, ${q(bcrypt.hashSync(DEMO.admin.password, 10))}, null, null);
`;

// Yesterday's submitted runsheets + today's trips in progress.
// [driverNo, dayOffset, job, pickup, dropoff, entryId, exitId, confidence, needsCheck, minutesAfter7am]
const trips = [
  ["104", 1, "A-4461", "12 Lakeside Dr, Ringwood VIC", "455 Burwood Hwy, Vermont South VIC", 202, 206, 91, false, 35],
  ["104", 1, "A-4463", "8 Somerton Rd, Somerton VIC", "190 Bridge Rd, Richmond VIC", 101, 110, 82, false, 140],
  ["104", 1, "A-4466", "21 Whiteman St, Southbank VIC", "600 Toorak Rd, Toorak VIC", 108, 116, 88, false, 230],
  ["104", 1, "A-4468", "50 Ferntree Gully Rd, Oakleigh East VIC", "15 Greens Rd, Dandenong South VIC", 208, 215, 79, false, 330],
  ["104", 1, "A-4470", "2 Francis St, Yarraville VIC", "800 Collins St, Docklands VIC", 301, 303, 74, false, 420],
  ["117", 1, "B-2210", "33 Dandenong Valley Hwy, Bangholme VIC", "1 Maroondah Hwy, Ringwood VIC", 216, 203, 86, false, 60],
  ["117", 1, "B-2214", "200 Kings Way, South Melbourne VIC", "40 Pascoe Vale Rd, Strathmore VIC", 106, 101, 90, false, 200],
  ["117", 1, "B-2219", "9 Wellington Rd, Rowville VIC", "70 Canterbury Rd, Vermont VIC", 209, 204, 84, false, 380],
  ["104", 0, "A-4471", "5 Mt Dandenong Rd, Ringwood East VIC", "455 Burwood Hwy, Vermont South VIC", 202, 206, 90, false, 52],
  ["104", 0, "A-4475", "1 Bolte Dr, Docklands VIC", "350 Bell St, Pascoe Vale VIC", 106, 101, 87, false, 198],
  ["104", 0, "A-4477", "60 Swan St, Burnley VIC", "120 Toorak Rd, South Yarra VIC", 108, 115, 58, true, 340],
];

for (const [no, back] of [["104", 1], ["117", 1]]) {
  const count = trips.filter((t) => t[0] === no && t[1] === back).length;
  out += `
insert into runsheets (driver_id, sheet_date, trip_count, submitted_at)
select id, ${today} - ${back}, ${count}, ((${today} - ${back}) + time '17:40') at time zone 'Australia/Melbourne' from users where driver_no = ${q(no)};`;
}

const driver = Object.fromEntries(DEMO.drivers.map((d) => [d.no, d]));
out += `\n\ninsert into trips (driver_id, trip_date, job_number, toll_account, truck_rego, pickup_address, dropoff_address,
  entry_point_id, exit_point_id, suggested_entry_id, suggested_exit_id, confidence, suggestion_reason, needs_check, runsheet_id, created_at, updated_at)\n`;
out += trips
  .map(([no, back, job, pu, drop, en, ex, conf, chk, mins]) => {
    const d = driver[no];
    const date = `${today} - ${back}`;
    // Past days: fixed times in the shift. Today: a few hours before "now", so the demo never shows future times.
    const at = back > 0
      ? `((${date}) + time '07:00' + interval '${mins} minutes') at time zone 'Australia/Melbourne'`
      : `now() - interval '${Math.round((400 - mins) / 2)} minutes'`;
    const sheet = back > 0 ? `(select r.id from runsheets r join users u on u.id = r.driver_id where u.driver_no = ${q(no)} and r.sheet_date = ${date})` : "null";
    const reason = chk ? "Two exits are about the same distance from the drop-off. Please check which one you used." : "Demo trip.";
    return `select (select id from users where driver_no = ${q(no)}), ${date}, ${q(job)}, ${q(d.acct)}, ${q(d.rego)}, ${q(pu)}, ${q(drop)}, ${en}, ${ex}, ${en}, ${ex}, ${conf}, ${q(reason)}, ${chk}, ${sheet}, ${at}, ${at}`;
  })
  .join("\nunion all ");
out += ";\n";

fs.writeFileSync(path.join(root, "db/seed.sql"), out);
console.log("wrote db/seed.sql");
